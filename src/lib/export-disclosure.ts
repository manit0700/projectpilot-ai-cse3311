import {
  draftNote, eventsOf, exportDate, hasHumanEditedField, isHumanEdited, modeLabel, modelLabel, modelsUsed, NOT_RECORDED, orderedTasks, planSlug,
  requirementRef, resolveMode, shortTitle, taskTitle, usageOf, type ExportMode, type ExportOptions,
} from "./export-common";
import type { SessionEvent } from "./session-log";
import type { WorkflowState } from "./workflow";

// AI-use disclosure for class AI-use policies. Everything comes from recorded events or the final
// plan; when something was not recorded the document says so instead of guessing.

export interface DraftStats { drafts: number; accepted: number; edited: number; rejected: number; undecided: number }
const EMPTY: DraftStats = { drafts: 0, accepted: 0, edited: 0, rejected: 0, undecided: 0 };

/**
 * Per drafted item: rejected, edited then approved, accepted unchanged, or still undecided.
 * Items with no approve/reject events (clarifying answers) count as accepted once the author moved on
 * (`continued`), edited if an edit event exists, and undecided otherwise. They are never rejected.
 */
export function draftStats(events: SessionEvent[], types: { draft: string; edit: string; approve?: string; reject?: string }, continued = true): DraftStats {
  const drafted = new Set(events.filter((e) => e.type === types.draft && e.entityId).map((e) => e.entityId as string));
  const stats = { ...EMPTY };
  for (const id of drafted) {
    const mine = events.filter((e) => e.entityId === id);
    const edited = mine.some((e) => e.type === types.edit);
    stats.drafts++;
    if (!types.approve) {
      if (edited && continued) stats.edited++;
      else if (continued) stats.accepted++;
      else stats.undecided++;
      continue;
    }
    const decisions = mine.filter((e) => e.type === types.approve || (types.reject !== undefined && e.type === types.reject));
    const last = decisions[decisions.length - 1];
    if (!last) stats.undecided++;
    else if (last.type === types.reject) stats.rejected++;
    else if (edited) stats.edited++;
    else stats.accepted++;
  }
  return stats;
}

const ANSWER_TYPES = { draft: "answer_drafted", edit: "answer_edited" };
const REQUIREMENT_TYPES = { draft: "requirement_drafted", edit: "requirement_edited", approve: "requirement_approved", reject: "requirement_rejected" };
const OUTPUT_TYPES = { draft: "output_generated", edit: "output_edited", approve: "output_approved", reject: "output_rejected" };

/** The three rows of the decision table; null when there is no event log at all. */
export function decisionRows(events: SessionEvent[]): Array<[string, DraftStats]> | null {
  if (!events.length) return null;
  // Answers are accepted once the author moved past Clarify, which is when requirements get drafted.
  const continued = events.some((e) => e.type === "requirement_drafted");
  return [
    ["Clarifying answers drafted by AI", draftStats(events, ANSWER_TYPES, continued)],
    ["Requirements drafted by AI", draftStats(events, REQUIREMENT_TYPES)],
    ["Agent outputs generated by AI", draftStats(events, OUTPUT_TYPES)],
  ];
}

const AI_TYPES = new Set(["answer_drafted", "requirement_drafted", "output_generated", "review_completed"]);

export interface DisclosureNumbers { approved: number; total: number; edited: number | null; fromEvents: boolean }

/** N of M: requirements and agent outputs the author approved, and how many were edited. */
export function disclosureNumbers(s: WorkflowState): DisclosureNumbers {
  const events = eventsOf(s);
  const rows = decisionRows(events);
  if (rows) {
    // Same numbers as the table: sum its columns.
    const sum = (key: keyof DraftStats) => rows.reduce((total, [, stats]) => total + stats[key], 0);
    return { approved: sum("accepted") + sum("edited"), total: sum("drafts"), edited: sum("edited"), fromEvents: true };
  }
  const approved = s.requirements.filter((r) => r.approvalStatus === "approved").length + s.outputs.filter((o) => o.approved === "approved").length;
  const edited = hasHumanEditedField(s) ? s.outputs.filter((o) => isHumanEdited(s, o)).length : null;
  return { approved, total: s.requirements.length + s.outputs.length, edited, fromEvents: false };
}

export function disclosureStatement(s: WorkflowState, opts?: ExportOptions): string {
  const mode = resolveMode(s, opts);
  const models = modelsUsed(s);
  const tool = mode === "demo" && !models.length ? "ProjectPilot AI's prepared demo responses; no AI model was called" : models.length ? models.join("; ") : `ProjectPilot AI, model ${NOT_RECORDED}`;
  const n = disclosureNumbers(s);
  return `This plan was drafted with AI assistance (${tool}). The author reviewed and approved ${n.approved} of ${n.total} items and edited ${n.edited === null ? NOT_RECORDED : n.edited}.`;
}

const cellText = (value: unknown): string => String(value ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
const labelFor = (s: WorkflowState): ((id: string | undefined) => string) => {
  const map = new Map<string, string>();
  s.questions.forEach((q, i) => map.set(q.id, `Q${i + 1}`));
  s.requirements.forEach((r, i) => map.set(r.id, requirementRef(i)));
  for (const t of s.tasks) map.set(t.id, taskTitle(t).split(" · ")[0]);
  for (const o of s.outputs) { const t = s.tasks.find((x) => x.id === o.taskId); if (t) map.set(o.id, `${taskTitle(t).split(" · ")[0]} output`); }
  return (id) => (id ? map.get(id) ?? "item" : "-");
};

function who(e: SessionEvent, mode: ExportMode): string {
  if (AI_TYPES.has(e.type)) {
    if (e.provider || e.model) return `AI (${modelLabel(e)})`;
    return e.mode === "demo" || mode === "demo" ? "AI (prepared demo response)" : `AI (model ${NOT_RECORDED})`;
  }
  return e.type === "run_failed" || e.type === "run_stopped" ? "System" : "Author";
}

const TIMELINE_LIMIT = 300;

export function aiDisclosureMarkdown(s: WorkflowState, opts?: ExportOptions): string {
  const events = eventsOf(s);
  const mode = resolveMode(s, opts);
  const label = labelFor(s);
  const draft = draftNote(s);
  const sections: string[] = [
    `# AI-use disclosure: ${shortTitle(s.project)}${draft ? ` ${draft}` : ""}`,
    `Mode: ${modeLabel(mode)} · Exported: ${exportDate(opts)} · Events recorded: ${events.length || NOT_RECORDED}`,
    "## Statement", `> ${disclosureStatement(s, opts)}`,
  ];
  const n = disclosureNumbers(s);
  if (!n.fromEvents) sections.push(`_The event log is empty, so these counts come from the final plan (approved items and recorded human edits), not from a decision history._`);

  // Accept / edit / reject table.
  const rows = decisionRows(events) ?? [];
  sections.push("## AI drafts and human decisions", rows.length
    ? ["| Item type | AI drafts | Accepted unchanged | Edited then accepted | Rejected | Not yet decided |", "|---|---|---|---|---|---|", ...rows.map(([name, t]) => `| ${name} | ${t.drafts} | ${t.accepted} | ${t.edited} | ${t.rejected} | ${t.undecided} |`)].join("\n")
    : `Decision history: ${NOT_RECORDED}.`);

  // Models.
  const perModel = new Map<string, { count: number; what: Set<string> }>();
  for (const e of events) {
    if (!AI_TYPES.has(e.type) || !(e.provider || e.model)) continue;
    const key = modelLabel(e), row = perModel.get(key) ?? { count: 0, what: new Set<string>() };
    row.count++; row.what.add(e.type.replace(/_/g, " ")); perModel.set(key, row);
  }
  const unattributed = modelsUsed(s).filter((m) => !perModel.has(m));
  sections.push("## Models and providers", perModel.size || unattributed.length
    ? ["| Provider / model | Produced | Calls |", "|---|---|---|", ...[...perModel].map(([m, r]) => `| ${cellText(m)} | ${[...r.what].join(", ")} | ${r.count} |`), ...unattributed.map((m) => `| ${cellText(m)} | ${NOT_RECORDED} | ${NOT_RECORDED} |`)].join("\n")
    : mode === "demo" ? "None. Demo mode uses prepared responses; no AI model was called." : `Provider and model: ${NOT_RECORDED}.`);

  // Usage.
  const usage = usageOf(s);
  const sum = (key: "promptTokens" | "completionTokens" | "latencyMs") => { const values = events.map((e) => e[key]).filter((v): v is number => typeof v === "number"); return values.length ? values.reduce((a, b) => a + b, 0) : null; };
  const requests = usage?.requests ?? (events.some((e) => e.provider || e.model) ? events.filter((e) => AI_TYPES.has(e.type) && (e.provider || e.model)).length : null);
  const prompt = usage?.promptTokens ?? sum("promptTokens"), completion = usage?.completionTokens ?? sum("completionTokens"), latency = usage?.totalLatencyMs ?? sum("latencyMs");
  const demoNone = mode === "demo" && !requests;
  sections.push("## Usage", [
    `- Model requests: ${demoNone ? "0 (demo mode)" : requests ?? NOT_RECORDED}`,
    `- Prompt tokens: ${demoNone ? "0 (demo mode)" : prompt ?? NOT_RECORDED}`,
    `- Completion tokens: ${demoNone ? "0 (demo mode)" : completion ?? NOT_RECORDED}`,
    `- Total model time: ${demoNone ? "0 s (demo mode)" : latency === null ? NOT_RECORDED : `${(latency / 1000).toFixed(1)} s`}`,
  ].join("\n"));

  // Human edits.
  const edited = orderedTasks(s).flatMap((t) => s.outputs.filter((o) => o.taskId === t.id && isHumanEdited(s, o)).slice(0, 1).map(() => taskTitle(t)));
  sections.push("## Outputs edited by the author", edited.length ? edited.map((e) => `- ${e}`).join("\n") : events.length || hasHumanEditedField(s) ? "None." : `Edits: ${NOT_RECORDED}.`);

  // Timeline.
  const shown = events.slice(0, TIMELINE_LIMIT);
  sections.push("## Timeline (who, what, when)", events.length
    ? ["| When (UTC) | Who | What | Item | Note |", "|---|---|---|---|---|", ...shown.map((e) => `| ${cellText(e.at).replace("T", " ").replace(/\.\d+Z?$/, "Z")} | ${cellText(who(e, mode))} | ${e.type.replace(/_/g, " ")} | ${label(e.entityId)} | ${cellText(e.detail ?? "").slice(0, 120)} |`), ...(events.length > shown.length ? [`\n${events.length - shown.length} more events are in the session log export.`] : [])].join("\n")
    : `Timeline: ${NOT_RECORDED}.`);
  return sections.join("\n\n") + "\n";
}

export const disclosureFilename = (s: WorkflowState): string => `${planSlug(s)}-ai-use.md`;
